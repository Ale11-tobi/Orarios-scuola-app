document.getElementById('notify-btn').addEventListener('click', () => {
    if ('Notification' in window) {
        Notification.requestPermission().then(permission => {
            if (permission === 'granted') {
                alert('Avvisi attivati! Riceverai una notifica se hai l\'app in background.');
            }
        });
    } else {
        alert('Il browser non supporta le notifiche.');
    }
});

let notificationSentToday = false;
function checkScheduledNotifications() {
    const now = new Date();
    if (now.getHours() === 0 && now.getMinutes() === 0) notificationSentToday = false;

    if (!notificationSentToday && now.getHours() === 7 && now.getMinutes() === 50) {
        const day = now.getDay();
        if (day >= 1 && day <= 5) {
            const firstLesson = timetableData[currentClass][day][0];
            if (Notification.permission === 'granted') {
                new Notification('Prima Ora: ' + firstLesson.subject, {
                    body: 'Devi andare in aula ' + firstLesson.room,
                    icon: 'icon-192.png'
                });
                notificationSentToday = true;
            }
        }
    }
}

