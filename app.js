function getSubjectMeta(subject) {
    for (const key in subjectMeta) {
        if (subject.includes(key)) return subjectMeta[key];
    }
    return { emoji: "📘", color: "#8E8E93", bgAlpha: "rgba(142, 142, 147, 0.15)" };
}

let currentClass = localStorage.getItem('selectedClass') || '2L';
let selectedDay = new Date().getDay();
if (selectedDay === 0 || selectedDay === 6) selectedDay = 1;

const daysMap = ['Domenica', 'Lunedì', 'Martedì', 'Mercoledì', 'Giovedì', 'Venerdì', 'Sabato'];
const monthsMap = ['Gen', 'Feb', 'Mar', 'Apr', 'Mag', 'Giu', 'Lug', 'Ago', 'Set', 'Ott', 'Nov', 'Dic'];

function timeToMinutes(timeStr) {
    const [h, m] = timeStr.split(':').map(Number);
    return h * 60 + m;
}

function calculateProgress(startStr, endStr, nowMins) {
    const start = timeToMinutes(startStr);
    const end = timeToMinutes(endStr);
    if (nowMins < start) return 0;
    if (nowMins >= end) return 100;
    return ((nowMins - start) / (end - start)) * 100;
}

function updateClock() {
    const now = new Date();
    document.getElementById('clock').innerText = now.toLocaleTimeString('it-IT', { hour: '2-digit', minute: '2-digit' });
    document.getElementById('date-display').innerText = `${daysMap[now.getDay()]}, ${now.getDate()} ${monthsMap[now.getMonth()]}`;
    updateStatus(now);
}

function updateStatus(now) {
    const day = now.getDay();
    const currentMins = now.getHours() * 60 + now.getMinutes();
    const container = document.getElementById('status-widgets');
    container.innerHTML = '';

    if (day === 0 || day === 6 || !timetableData[currentClass][day]) {
        container.innerHTML = `
            <div class="widget current">
                <div class="widget-bg-blob"></div>
                <div class="widget-label"><span class="widget-label-icon">🎉</span> Fine settimana</div>
                <div class="widget-main">
                    <div class="widget-subject">Nessuna lezione</div>
                </div>
            </div>`;
        return;
    }

    const lessons = timetableData[currentClass][day];
    let currentLesson = null;
    let nextLesson = null;

    for (let i = 0; i < lessons.length; i++) {
        const l = lessons[i];
        const start = timeToMinutes(l.start);
        const end = timeToMinutes(l.end);

        if (currentMins >= start && currentMins < end) {
            currentLesson = l;
            if (i + 1 < lessons.length) nextLesson = lessons[i+1];
            break;
        } else if (currentMins < start) {
            if (!nextLesson) nextLesson = l;
        }
    }

    if (currentLesson) {
        const meta = getSubjectMeta(currentLesson.subject);
        const progress = calculateProgress(currentLesson.start, currentLesson.end, currentMins);
        
        container.innerHTML += `
            <div class="widget current">
                <div class="widget-bg-blob"></div>
                <div class="widget-label">
                    <span class="widget-label-icon">🔴</span> IN CORSO
                </div>
                <div class="widget-main">
                    <div class="widget-subject">${meta.emoji} ${currentLesson.subject}</div>
                    <div class="widget-room">${currentLesson.room}</div>
                </div>
                <div class="widget-footer">
                    <span>Finisce alle ${currentLesson.end}</span>
                </div>
                <div class="progress-bar-container">
                    <div class="progress-bar" style="width: ${progress}%"></div>
                </div>
            </div>
        `;
    } else if (currentMins < timeToMinutes(lessons[0].start)) {
        const meta = getSubjectMeta(lessons[0].subject);
        container.innerHTML += `
            <div class="widget current">
                <div class="widget-bg-blob"></div>
                <div class="widget-label">
                    <span class="widget-label-icon">⏳</span> PRIMA ORA
                </div>
                <div class="widget-main">
                    <div class="widget-subject">${meta.emoji} ${lessons[0].subject}</div>
                    <div class="widget-room">${lessons[0].room}</div>
                </div>
                <div class="widget-footer">
                    <span>Inizia alle ${lessons[0].start}</span>
                </div>
            </div>
        `;
    } else {
        container.innerHTML += `
            <div class="widget current">
                <div class="widget-bg-blob"></div>
                <div class="widget-label"><span class="widget-label-icon">✅</span> COMPLETATO</div>
                <div class="widget-main">
                    <div class="widget-subject">Lezioni finite</div>
                </div>
            </div>
        `;
    }

    if (nextLesson && currentLesson) {
        const meta = getSubjectMeta(nextLesson.subject);
        container.innerHTML += `
            <div class="widget next">
                <div class="widget-label" style="color: ${meta.color}">
                    <span class="widget-label-icon">⏭️</span> PROSSIMA
                </div>
                <div class="widget-main" style="margin-bottom:0">
                    <div class="widget-subject" style="font-size: 1.5rem">${meta.emoji} ${nextLesson.subject}</div>
                    <div class="widget-room" style="font-size: 1rem; border:none; background:rgba(255,255,255,0.05)">${nextLesson.room}</div>
                </div>
            </div>
        `;
    }
}

function renderTimetable(dayIndex) {
    const list = document.getElementById('timetable-list');
    list.innerHTML = '';
    
    document.querySelectorAll('.day-btn').forEach(btn => {
        btn.classList.toggle('active', parseInt(btn.dataset.day) === dayIndex);
    });

    const lessons = timetableData[currentClass][dayIndex] || [];
    const now = new Date();
    const currentMins = now.getHours() * 60 + now.getMinutes();
    const isToday = now.getDay() === dayIndex;

    lessons.forEach(l => {
        const start = timeToMinutes(l.start);
        const end = timeToMinutes(l.end);
        const isActive = isToday && currentMins >= start && currentMins < end;
        const meta = getSubjectMeta(l.subject);

        list.innerHTML += `
            <div class="lesson-item ${isActive ? 'active-lesson' : ''}" style="--item-color: ${meta.color}; --item-bg: ${meta.bgAlpha};">
                <div class="lesson-time">
                    <span class="time-start">${l.start}</span>
                    <span class="time-end">${l.end}</span>
                </div>
                <div class="lesson-content">
                    <div class="subject-wrapper">
                        <div class="subject-icon-box">${meta.emoji}</div>
                        <span class="lesson-subject">${l.subject}</span>
                    </div>
                    <span class="lesson-teachers">${l.teachers}</span>
                </div>
                <div class="lesson-room-badge">${l.room}</div>
            </div>
        `;
    });
}

document.querySelectorAll('.day-btn').forEach(btn => {
    btn.addEventListener('click', (e) => {
        selectedDay = parseInt(e.target.dataset.day);
        renderTimetable(selectedDay);
    });
});

